//! Generated-code markers (docs/proposals/archive/generated-code-markers.md): a
//! documented marker refines a module claim to `production:generated`, while
//! look-alikes that claimed hand-written code in the measurements stay
//! implementation (docs/research/generated-code-markers.md).
use crate::cli::*;
use serde_json::{json, Value};
use std::process::Command;

const IMPLEMENTATION: &str = "production:implementation";
const GENERATED: &str = "production:generated";

fn measured(files: &[(&str, &str)]) -> Value {
    let temp = project(files);
    let (success, document, stderr) = report(&temp.path().join("project"), &[]);
    assert!(success, "{stderr}");
    document
}

fn file<'a>(document: &'a Value, path: &str) -> &'a Value {
    document["files"]
        .as_array()
        .unwrap()
        .iter()
        .find(|file| file["path"] == path)
        .unwrap_or_else(|| panic!("{path} is not in the report"))
}

/// `(path, purpose:category, rule)` for each expected path.
fn expect(document: &Value, expected: &[(&str, &str, &str)]) {
    let actual: Vec<(String, String, String)> = expected
        .iter()
        .map(|(path, _, _)| {
            let file = file(document, path);
            (
                path.to_string(),
                format!(
                    "{}:{}",
                    file["purpose"].as_str().unwrap(),
                    file["category"].as_str().unwrap()
                ),
                file["rule"].as_str().unwrap().into(),
            )
        })
        .collect();
    let expected: Vec<(String, String, String)> = expected
        .iter()
        .map(|(path, class, rule)| (path.to_string(), class.to_string(), rule.to_string()))
        .collect();
    assert_eq!(actual, expected);
}

/// Go's line must stand before the first code line and end with
/// `DO NOT EDIT.`; gopls's hand-written generator carries it after the
/// `package` clause, in its output template.
#[test]
fn go_header_marks_only_files_whose_leading_comments_carry_it() {
    let document = measured(&[
        ("go.mod", "module example.com/app\n"),
        (
            "api/api.pb.go",
            "// Copyright 2026 Example.\n\n// Code generated by protoc-gen-go. DO NOT EDIT.\n// source: api.proto\n\npackage api\n\nvar A = 1\n",
        ),
        (
            "gen/gen.go",
            "package gen\n\nconst header = `\n// Code generated by gen. DO NOT EDIT.\n`\n",
        ),
        (
            "loose/loose.go",
            "// Code generated by hand, edit freely.\npackage loose\n\nvar B = 2\n",
        ),
        (
            "api/api_test.go",
            "// Code generated by mockgen. DO NOT EDIT.\npackage api\n",
        ),
    ]);
    expect(
        &document,
        &[
            ("api/api.pb.go", GENERATED, "builtin:go-generated-header"),
            ("gen/gen.go", IMPLEMENTATION, "builtin:go-module"),
            ("loose/loose.go", IMPLEMENTATION, "builtin:go-module"),
            ("api/api_test.go", "test:test", "builtin:go-test-file"),
        ],
    );
    // The module keeps its credit, but only layout-decided files are listed for review.
    assert_eq!(
        file(&document, "api/api.pb.go")["module"],
        json!({"path": ".", "detector": "go"})
    );
    let listed: Vec<&str> = document["summary"]["largest_module_files"]
        .as_array()
        .unwrap()
        .iter()
        .map(|file| file["path"].as_str().unwrap())
        .collect();
    assert!(!listed.contains(&"api/api.pb.go"), "{listed:?}");
}

/// Roslyn's names are case-insensitive and cover Visual Basic; its comment
/// check reads past the byte-order mark EF Core writes.
#[test]
fn roslyn_names_and_auto_generated_comments_mark_dotnet_source() {
    let document = measured(&[
        ("Api/Api.csproj", "<Project />\n"),
        ("Api/Home.cs", "class Home {}\n"),
        ("Api/Form1.designer.vb", "Class Form1\nEnd Class\n"),
        ("Api/Api.G.cs", "class Api {}\n"),
        ("Api/TemporaryGeneratedFile_1.cs", "class T {}\n"),
        (
            "Api/Migrations/AppDbContextModelSnapshot.cs",
            "\u{feff}// <auto-generated />\nusing System;\n\nclass Snapshot {}\n",
        ),
        (
            "Api/Resources.cs",
            "//------------------------------------------------------------------------------\n// <autogenerated>\n//     This code was generated by a tool.\n// </autogenerated>\n//------------------------------------------------------------------------------\nclass Resources {}\n",
        ),
        (
            "Api/Writer.cs",
            "class Writer {\n    const string Header = \"// <auto-generated />\";\n}\n",
        ),
    ]);
    expect(
        &document,
        &[
            ("Api/Home.cs", IMPLEMENTATION, "builtin:dotnet-module"),
            (
                "Api/Form1.designer.vb",
                GENERATED,
                "builtin:roslyn-generated",
            ),
            ("Api/Api.G.cs", GENERATED, "builtin:roslyn-generated"),
            (
                "Api/TemporaryGeneratedFile_1.cs",
                GENERATED,
                "builtin:roslyn-generated",
            ),
            (
                "Api/Migrations/AppDbContextModelSnapshot.cs",
                GENERATED,
                "builtin:roslyn-generated",
            ),
            ("Api/Resources.cs", GENERATED, "builtin:roslyn-generated"),
            ("Api/Writer.cs", IMPLEMENTATION, "builtin:dotnet-module"),
        ],
    );
}

/// Java SE's `@Generated` can also mark generated parts of a hand-written
/// file, so only the annotation on the first top-level type marks the file,
/// and only from the documented packages.
#[test]
fn java_generated_annotation_marks_only_the_annotated_top_level_type() {
    let document = measured(&[
        ("pom.xml", "<project />\n"),
        (
            "src/main/java/a/Model.java",
            "package a;\n\nimport java.util.List;\n\n@jakarta.annotation.Generated(value = \"org.openapitools.codegen.languages.SpringCodegen\", comments = \"see https://openapi-generator.tech\")\n@Schema(name = \"Model\", allowableValues = { \"a\", \"b\" })\npublic class Model {}\n",
        ),
        (
            "src/main/java/a/Mapper.java",
            "package a;\n\nimport javax.annotation.processing.Generated;\n\n@Deprecated\n@Generated(\n    value = \"org.mapstruct.ap.MappingProcessor\",\n    date = \"2022-06-06T16:48:23+0200\"\n)\n@Custom(values = { \"x\", \"y\" })\npublic final class Mapper {}\n",
        ),
        (
            "src/main/java/a/Partly.java",
            "package a;\n\nimport javax.annotation.processing.Generated;\n\npublic class Partly {\n    @Generated(\"tool\")\n    int x;\n}\n",
        ),
        (
            "src/main/java/a/Lombok.java",
            "package a;\n\nimport lombok.Generated;\n\n@Generated\npublic class Lombok {}\n",
        ),
        (
            "src/main/java/a/Text.java",
            "package a;\n\n/** Emits {@code @javax.annotation.Generated(\"x\")} on generated classes. */\npublic class Text {\n    String s = \"@javax.annotation.Generated(\\\"x\\\")\";\n}\n",
        ),
    ]);
    expect(
        &document,
        &[
            (
                "src/main/java/a/Model.java",
                GENERATED,
                "builtin:java-generated-annotation",
            ),
            (
                "src/main/java/a/Mapper.java",
                GENERATED,
                "builtin:java-generated-annotation",
            ),
            (
                "src/main/java/a/Partly.java",
                IMPLEMENTATION,
                "builtin:maven-module",
            ),
            (
                "src/main/java/a/Lombok.java",
                IMPLEMENTATION,
                "builtin:maven-module",
            ),
            (
                "src/main/java/a/Text.java",
                IMPLEMENTATION,
                "builtin:maven-module",
            ),
        ],
    );
}

/// Git's precedence: later lines and deeper files win, and an explicit
/// `-linguist-generated` or `=false` declares a file not generated, even
/// against a marker in its content, as it overrides GitHub Linguist's own
/// checks (Linguist `lazy_blob.rb`, `generated?`).
#[test]
fn gitattributes_declarations_follow_git_precedence() {
    let document = measured(&[
        ("package.json", "{}\n"),
        (
            ".gitattributes",
            "# Generated clients\nsrc/client/** linguist-generated=true\n*.gen.ts linguist-generated\nsrc/client/hand.ts -linguist-generated\nsrc/client/kept.ts linguist-generated=false\n*.lock linguist-generated -merge\nhand/*.go -linguist-generated\n",
        ),
        ("src/client/api.ts", "export const a = 1;\n"),
        ("src/client/hand.ts", "export const b = 2;\n"),
        ("src/client/kept.ts", "export const c = 3;\n"),
        ("src/deep/types.gen.ts", "export type T = 1;\n"),
        (
            "src/deep/.gitattributes",
            "types.gen.ts !linguist-generated\nlocal.ts linguist-generated\n",
        ),
        ("src/deep/local.ts", "export const d = 4;\n"),
        ("src/other.gen.ts", "export const e = 5;\n"),
        ("src/app.ts", "export const f = 6;\n"),
        ("go.mod", "module example.com/x\n"),
        (
            "hand/h.go",
            "// Code generated by tool. DO NOT EDIT.\npackage hand\n",
        ),
    ]);
    expect(
        &document,
        &[
            ("src/client/api.ts", GENERATED, "builtin:linguist-generated"),
            ("src/client/hand.ts", IMPLEMENTATION, "builtin:npm-module"),
            ("src/client/kept.ts", IMPLEMENTATION, "builtin:npm-module"),
            (
                "src/deep/types.gen.ts",
                IMPLEMENTATION,
                "builtin:npm-module",
            ),
            ("src/deep/local.ts", GENERATED, "builtin:linguist-generated"),
            ("src/other.gen.ts", GENERATED, "builtin:linguist-generated"),
            ("src/app.ts", IMPLEMENTATION, "builtin:npm-module"),
            ("hand/h.go", IMPLEMENTATION, "builtin:go-module"),
        ],
    );
}

/// A `.gitattributes` file's patterns are anchored to its folder by name, so
/// glob characters in that name match only themselves: unescaped, the
/// patterns in `gen[1]` would match `gen1` and miss the folder's own files.
#[test]
fn gitattributes_patterns_anchor_to_their_folder_literally() {
    let document = measured(&[
        ("go.mod", "module example.com/x\n"),
        ("gen[1]/.gitattributes", "*.go linguist-generated\n"),
        ("gen[1]/a.go", "package gen\n"),
        ("gen1/b.go", "package gen\n"),
    ]);
    expect(
        &document,
        &[
            ("gen[1]/a.go", GENERATED, "builtin:linguist-generated"),
            ("gen1/b.go", IMPLEMENTATION, "builtin:go-module"),
        ],
    );
}

/// Overrides, conventions and rules decide first, and the switch turns the
/// markers off; reports record the applied marker set.
#[test]
fn earlier_stages_win_and_the_switch_disables_markers() {
    const HEADER: &str = "// Code generated by tool. DO NOT EDIT.\npackage x\n";
    let files = |config: &'static str| {
        vec![
            (".locmetryrc", config),
            ("go.mod", "module example.com/x\n"),
            ("gen/a.go", HEADER),
            ("ruled/b.go", HEADER),
        ]
    };
    let rule = "version = 1\n[[rules]]\nid = \"vendored\"\nmatch = [\"ruled/**\"]\npurpose = \"other\"\ncategory = \"vendored\"\n";
    let document = measured(&files(rule));
    expect(
        &document,
        &[
            ("gen/a.go", GENERATED, "builtin:go-generated-header"),
            ("ruled/b.go", "other:vendored", "vendored"),
        ],
    );
    assert_eq!(
        document["metadata"]["config"]["builtin_generated_markers"],
        json!([
            "builtin:go-generated-header",
            "builtin:roslyn-generated",
            "builtin:java-generated-annotation",
            "builtin:linguist-generated"
        ])
    );
    let document = measured(&files(
        "version = 1\n[classification]\nbuiltin_generated = false\n",
    ));
    expect(
        &document,
        &[("gen/a.go", IMPLEMENTATION, "builtin:go-module")],
    );
    assert_eq!(
        document["metadata"]["config"]["builtin_generated_markers"],
        json!([])
    );
}

#[test]
fn explain_shows_the_marker_and_its_evidence() {
    let temp = project(&[
        ("go.mod", "module example.com/x\n"),
        (
            "gen/a.go",
            "// Code generated by tool. DO NOT EDIT.\npackage gen\n",
        ),
        ("package.json", "{}\n"),
        (".gitattributes", "src/client/** linguist-generated\n"),
        ("src/client/api.ts", "export const a = 1;\n"),
    ]);
    let root = temp.path().join("project");
    let explain = |path: &str, format: &str| {
        let output = Command::new(env!("CARGO_BIN_EXE_locmetry"))
            .args(["explain", path, "--no-user-config", "--format", format])
            .current_dir(&root)
            .output()
            .unwrap();
        assert!(
            output.status.success(),
            "{}",
            String::from_utf8_lossy(&output.stderr)
        );
        String::from_utf8(output.stdout).unwrap()
    };
    let json: Value = serde_json::from_str(&explain("gen/a.go", "json")).unwrap();
    assert_eq!(
        json["result"]["file"]["rule"],
        "builtin:go-generated-header"
    );
    assert_eq!(json["result"]["decision"]["stage"], "module");
    assert_eq!(
        json["result"]["decision"]["generated"],
        json!({
            "marker": "builtin:go-generated-header",
            "evidence": "// Code generated by tool. DO NOT EDIT."
        })
    );
    let text = explain("gen/a.go", "table");
    assert!(
        text.contains(
            "Generated marker: builtin:go-generated-header, from '// Code generated by tool. DO NOT EDIT.'\n"
        ),
        "{text}"
    );
    let json: Value = serde_json::from_str(&explain("src/client/api.ts", "json")).unwrap();
    assert_eq!(
        json["result"]["decision"]["generated"],
        json!({
            "marker": "builtin:linguist-generated",
            "evidence": ".gitattributes: src/client/** linguist-generated"
        })
    );
}
