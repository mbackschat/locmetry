use crate::{Counts, Coverage, FileRecord, Kind, Purpose, ReportSummary};
use anyhow::{ensure, Context, Result};
use serde_json::Value;
use std::{
    collections::BTreeMap,
    fmt::Write,
    fs,
    path::{Path, PathBuf},
};

fn cell(value: &str) -> String {
    value
        .replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
        .replace('|', "&#124;")
        .replace('`', "&#96;")
        .replace(['\r', '\n'], " ")
}

fn count_row(output: &mut String, label: &str, counts: &Counts) {
    writeln!(
        output,
        "| {} | {} | {} | {} | {} | {} |",
        cell(label),
        counts.files,
        counts.code,
        counts.comments,
        counts.blanks,
        counts.lines
    )
    .unwrap();
}

fn table(output: &mut String, title: &str, label: &str, counts: &BTreeMap<String, Counts>) {
    writeln!(output, "\n## {title}\n\n| {label} | Files | Code | Comments | Blanks | Lines |\n| --- | ---: | ---: | ---: | ---: | ---: |").unwrap();
    for (label, counts) in counts {
        count_row(output, label, counts);
    }
}

pub fn render_markdown(
    project: &str,
    summary: &ReportSummary,
    rows: &[FileRecord],
    coverage: &Coverage,
    depth: usize,
) -> String {
    let mut output = format!("# {} measured classification\n\nGenerated by Locmetry with embedded Tokei. Production means maintained non-test source, including separately categorized tooling and examples. These are path-rule assignments; unclassified source stays visible. Embedded snippets inherit the host file's kind and purpose. Data/configuration and documentation do not contribute to source subtotals.\n\nUntracked files are included; hidden-file, ignore-file, and exclusion settings are recorded in the JSON metadata. Ambient Tokei configuration is not loaded. Counts describe the current working copy, not a commit snapshot. Unsupported files are not proven zero LOC.\n\n## Source purpose\n\n| Purpose | Files | Code | Comments | Blanks | Lines |\n| --- | ---: | ---: | ---: | ---: | ---: |\n", cell(project));
    for purpose in Purpose::ALL {
        count_row(
            &mut output,
            &purpose.to_string(),
            &summary.totals.purpose(purpose),
        );
    }
    table(
        &mut output,
        "Source categories",
        "Category",
        &summary.totals.source_categories,
    );
    let other = summary
        .totals
        .by_kind_purpose
        .iter()
        .filter(|(key, _)| !key.starts_with("source:"))
        .map(|(key, value)| (key.clone(), *value))
        .collect();
    table(&mut output, "Other counted content", "Kind:purpose", &other);
    table(
        &mut output,
        "Source languages",
        "Language",
        &summary.totals.source_languages,
    );
    write!(output, "\n## Folder breakdown\n\nRecursive source code totals to depth {depth}. Parent rows include their children; do not sum all displayed rows. JSON includes direct and recursive totals at every depth. Multi-language files count once physically but contribute to each contained language.\n\n| Folder | Production | Test | Unclassified | Total source code |\n| --- | ---: | ---: | ---: | ---: |\n").unwrap();
    for (folder, values) in &summary.folders {
        let totals = &values.recursive;
        if folder.split('/').count() > depth || totals.source.files == 0 {
            continue;
        }
        writeln!(
            output,
            "| {} | {} | {} | {} | {} |",
            cell(folder),
            totals.purpose(Purpose::Production).code,
            totals.purpose(Purpose::Test).code,
            totals.purpose(Purpose::Unclassified).code,
            totals.source.code
        )
        .unwrap();
    }
    let mut unknown: Vec<_> = rows
        .iter()
        .filter(|r| r.kind == Kind::Source && r.classification.purpose == Purpose::Unclassified)
        .collect();
    unknown.sort_by(|a, b| b.counts.code.cmp(&a.counts.code).then(a.path.cmp(&b.path)));
    writeln!(output, "\n## Source requiring review\n\n{} files. Largest 25 below; all file records and rule provenance are in JSON.\n\n| Path | Code | Category |\n| --- | ---: | --- |", unknown.len()).unwrap();
    for row in unknown.into_iter().take(25) {
        writeln!(
            output,
            "| {} | {} | {} |",
            cell(&row.path),
            row.counts.code,
            cell(&row.classification.category)
        )
        .unwrap();
    }
    render_coverage(&mut output, coverage);
    output
}

fn render_coverage(output: &mut String, coverage: &Coverage) {
    writeln!(output, "\n## Coverage\n\n{} files selected, {} counted, {} of them through language mappings. {} were not recognized and {} recognized files could not be read; their lines are missing, not zero.", coverage.selected_files, coverage.counted_files, coverage.mapped_files, coverage.unrecognized.len(), coverage.unread.len()).unwrap();
    let mut extensions = BTreeMap::<&str, usize>::new();
    for path in &coverage.unrecognized {
        let name = path.rsplit('/').next().unwrap_or(path);
        let extension = match name.rsplit_once('.') {
            Some((stem, extension)) if !stem.is_empty() => extension,
            _ => "(none)",
        };
        *extensions.entry(extension).or_default() += 1;
    }
    let mut extensions: Vec<_> = extensions.into_iter().collect();
    extensions.sort_by(|a, b| b.1.cmp(&a.1).then(a.0.cmp(b.0)));
    if !extensions.is_empty() {
        output.push_str("\n| Unrecognized extension | Files |\n| --- | ---: |\n");
        for (extension, files) in extensions.into_iter().take(15) {
            writeln!(output, "| {} | {files} |", cell(extension)).unwrap();
        }
    }
    if !coverage.unread.is_empty() {
        output.push_str("\n| Unreadable file |\n| --- |\n");
        for path in coverage.unread.iter().take(25) {
            writeln!(output, "| {} |", cell(path)).unwrap();
        }
    }
}

fn resolve_destination(path: &Path) -> Result<PathBuf> {
    if fs::symlink_metadata(path).is_ok() {
        return Ok(path.canonicalize()?);
    }
    let name = path.file_name().context("Invalid output path")?;
    let parent = path
        .parent()
        .filter(|p| !p.as_os_str().is_empty())
        .unwrap_or(Path::new("."));
    Ok(resolve_destination(parent)?.join(name))
}

/// Report files written for an output prefix.
///
/// Suffixes are appended to the whole file name rather than replacing its
/// extension, so `run.v1` and `run.v2` stay distinct.
fn destinations(output: &Path) -> Result<[PathBuf; 3]> {
    let name = output.file_name().context("Invalid output path")?;
    let with_suffix = |suffix: &str| {
        let mut name = name.to_owned();
        name.push(suffix);
        output.with_file_name(name)
    };
    Ok([
        with_suffix(".json"),
        with_suffix(".md"),
        with_suffix(".tokei.json"),
    ])
}

pub fn validate_output(output: &Path, root: &Path, config: Option<&Path>) -> Result<PathBuf> {
    let output = resolve_destination(output)?;
    let root = root.canonicalize()?;
    let config = config.map(Path::canonicalize).transpose()?;
    for destination in destinations(&output)? {
        let destination = resolve_destination(&destination)?;
        ensure!(
            !destination.starts_with(&root),
            "Output must be outside the read-only scan root"
        );
        ensure!(
            config.as_ref() != Some(&destination),
            "Output would overwrite the configuration: {}",
            destination.display()
        );
    }
    Ok(output)
}

pub fn write_reports(
    output: &Path,
    root: &Path,
    config: Option<&Path>,
    document: &Value,
    raw: &Value,
    markdown: &str,
) -> Result<[PathBuf; 3]> {
    let output = validate_output(output, root, config)?;
    fs::create_dir_all(output.parent().context("Missing output parent")?)?;
    let [json, md, tokei] = destinations(&output)?;
    fs::write(&json, format!("{}\n", serde_json::to_string(document)?))?;
    fs::write(&tokei, format!("{}\n", serde_json::to_string(raw)?))?;
    fs::write(&md, markdown)?;
    Ok([json, md, tokei])
}
