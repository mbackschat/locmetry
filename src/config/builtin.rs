//! Built-in exclusions, classification conventions and language mappings.
use super::Purpose;
use tokei::LanguageType;

/// Version control, dependency checkouts, and the build folders of SwiftPM
/// (`.build`) and Lake (`.lake`, which also holds dependency checkouts such as
/// mathlib).
pub(super) const DEFAULT_EXCLUDES: &[&str] = &[
    "**/.git/**",
    "**/node_modules/**",
    "**/.build/**",
    "**/.lake/**",
];

/// A built-in classification entry. The configuration `version` selects each
/// set, and releases may only add entries to it (docs/PRODUCT.md, `version`).
pub(super) struct Convention {
    pub(super) id: &'static str,
    pub(super) patterns: &'static [&'static str],
    pub(super) purpose: Purpose,
    pub(super) category: &'static str,
}

const fn test_convention(id: &'static str, patterns: &'static [&'static str]) -> Convention {
    Convention {
        id,
        patterns,
        purpose: Purpose::Test,
        category: "test",
    }
}

/// Version-1 test conventions.
///
/// Ambiguous names are deliberately absent: reference projects disagree on
/// whether `fixtures` hold tests, and one keeps specification tooling in a
/// `spec` folder (docs/PRODUCT.md; docs/research/loc-counting-tools.md).
pub(super) const BUILTIN_TESTS_V1: &[Convention] = &[
    test_convention("test-directory", &["**/{test,tests,__test__,__tests__}/**"]),
    test_convention(
        "gradle-test-source-set",
        &["**/src/*Test/**", "**/src/testFixtures/**"],
    ),
    test_convention("snapshot-directory", &["**/__snapshots__/**"]),
    test_convention(
        "js-test-file",
        &["**/*.{test,spec}.{js,jsx,mjs,cjs,ts,tsx,mts,cts}"],
    ),
    // NestJS scaffolds end-to-end suites as `*.e2e-spec.ts`, which the
    // `.spec` suffix above misses; Immich's `e2e/` suites follow it
    // (docs/proposals/archive/immich-showcase.md). A bare `-spec` suffix also names
    // specifications, so only this compound suffix is a test name.
    test_convention(
        "js-e2e-spec-file",
        &["**/*.e2e-spec.{js,jsx,mjs,cjs,ts,tsx,mts,cts}"],
    ),
    test_convention(
        "jvm-test-class",
        &["**/*{Test,Tests,TestCase}.{java,kt,kts,groovy,scala}"],
    ),
    test_convention("go-test-file", &["**/*_test.go"]),
    // Rust unit tests live in a `#[cfg(test)] mod tests` beside the code
    // (https://doc.rust-lang.org/book/ch11-03-test-organization.html); moved
    // out of line, that module is a `tests.rs` file inside the Cargo `src/`
    // layout, which module detection would otherwise claim as production.
    test_convention("rust-test-module", &["**/tests.rs"]),
    // Swift Package Manager keeps test targets in `Tests/`, and Xcode names
    // test targets `<Name>Tests`; both start with a capital T, which the
    // lowercase test-directory convention does not match.
    test_convention("swift-test-target", &["**/*Tests/**/*.swift"]),
    // Lake test libraries are named `<Name>Test` or `<Name>Tests`, such as
    // mathlib4's `MathlibTest/` and Batteries' `BatteriesTest/`.
    test_convention("lean-test-library", &["**/*{Test,Tests}/**/*.lean"]),
    // Flutter keeps device-driven tests in `integration_test/` beside `test/`
    // (https://docs.flutter.dev/testing/integration-tests).
    test_convention(
        "flutter-integration-test",
        &["**/integration_test/**/*.dart"],
    ),
    test_convention(
        "python-test-file",
        &["**/test_*.py", "**/*_test.py", "**/conftest.py"],
    ),
];

/// Version-1 build conventions, applied after test conventions.
///
/// Build scripts are maintained but are not implementation, and wrapper
/// scripts are generated by their build tool; every reference profile wrote
/// equivalent rules by hand (docs/research/loc-counting-tools.md).
pub(super) const BUILTIN_BUILD_V1: &[Convention] = &[
    Convention {
        id: "build-script",
        patterns: &[
            "**/{build,settings}.gradle",
            "**/{build,settings}.gradle.kts",
            "**/pom.xml",
            "**/CMakeLists.txt",
            "**/*.cmake",
            "**/{Makefile,makefile,GNUmakefile}",
            "**/lakefile.lean",
        ],
        purpose: Purpose::Production,
        category: "build-tooling",
    },
    Convention {
        id: "build-wrapper",
        patterns: &[
            "**/{gradlew,gradlew.bat,mvnw,mvnw.cmd}",
            "**/gradle/wrapper/**",
            "**/.mvn/wrapper/**",
        ],
        purpose: Purpose::Other,
        category: "third-party-wrapper",
    },
];

/// Version-1 language mappings for files Tokei 15.0.0 does not recognize.
///
/// Each was selected but uncounted in the reference projects' coverage reports
/// (docs/research/loc-counting-tools.md); the mapped language's syntax matches.
pub(super) const BUILTIN_LANGUAGES_V1: &[(&str, &[&str], LanguageType)] = &[
    ("gradle-script", &["**/*.gradle"], LanguageType::Groovy),
    ("jsonc", &["**/*.jsonc"], LanguageType::Json),
    ("json-lines", &["**/*.jsonl"], LanguageType::Json),
    ("java-properties", &["**/*.properties"], LanguageType::Ini),
];
