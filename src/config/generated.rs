//! Generated-code markers: documented signals that refine a module layout's
//! claim to `production` with category `generated`
//! (docs/built-in-detection.md#generated-code-markers). The configuration
//! `version` selects the set, like the conventions.
use super::{Classification, Purpose, BUILTIN};
use schemars::JsonSchema;
use serde::Serialize;

/// Category of module-claimed source that carries a marker.
pub(crate) const GENERATED_CATEGORY: &str = "generated";

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum GeneratedMarker {
    GoGeneratedHeader,
    RoslynGenerated,
    JavaGeneratedAnnotation,
    LinguistGenerated,
}

impl GeneratedMarker {
    /// The version-1 set; releases may only add to it.
    pub const V1: [Self; 4] = [
        Self::GoGeneratedHeader,
        Self::RoslynGenerated,
        Self::JavaGeneratedAnnotation,
        Self::LinguistGenerated,
    ];

    pub fn id(self) -> &'static str {
        match self {
            Self::GoGeneratedHeader => "go-generated-header",
            Self::RoslynGenerated => "roslyn-generated",
            Self::JavaGeneratedAnnotation => "java-generated-annotation",
            Self::LinguistGenerated => "linguist-generated",
        }
    }

    /// What the marker matches, for the configuration schema.
    pub fn matches(self) -> &'static str {
        match self {
            Self::GoGeneratedHeader => "Go source whose leading comments, before the first code line, include a line matching `^// Code generated .* DO NOT EDIT\\.$`, as `go help generate` defines",
            Self::RoslynGenerated => "C# and Visual Basic source named like `*.designer.cs`, `*.generated.cs`, `*.g.cs`, `*.g.i.cs` (ignoring case) or `TemporaryGeneratedFile_*`, or whose leading comments contain `<auto-generated` or `<autogenerated`, as Roslyn's analyzers decide",
            Self::JavaGeneratedAnnotation => "Java source whose first top-level type is annotated `@Generated` from `javax.annotation.processing`, `javax.annotation` or `jakarta.annotation`, by qualified name or import; annotations on members do not count",
            Self::LinguistGenerated => "any source a `.gitattributes` file inside the scan root marks `linguist-generated`, with Git's precedence; `-linguist-generated` or `linguist-generated=false` declares a file not generated, which also overrides the other markers",
        }
    }

    /// Provenance of the files the marker decides.
    pub fn rule(self) -> String {
        format!("{BUILTIN}{}", self.id())
    }
}

/// Serialized as its provenance, `builtin:<marker>`.
impl Serialize for GeneratedMarker {
    fn serialize<S: serde::Serializer>(&self, serializer: S) -> Result<S::Ok, S::Error> {
        serializer.serialize_str(&self.rule())
    }
}

/// The marker a file carries and the text that matched.
#[derive(Clone, Debug, Serialize, JsonSchema)]
#[serde(deny_unknown_fields)]
pub struct GeneratedEvidence {
    /// The marker's provenance, which becomes the file's `rule`.
    #[schemars(with = "String")]
    pub marker: GeneratedMarker,
    /// The matched comment line, file name or annotation, or the `.gitattributes` file and its line.
    pub evidence: String,
}

impl GeneratedEvidence {
    pub(crate) fn classification(&self) -> Classification {
        Classification {
            purpose: Purpose::Production,
            category: GENERATED_CATEGORY.into(),
            rule: self.marker.rule(),
        }
    }
}
