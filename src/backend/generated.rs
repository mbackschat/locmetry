//! Generated-code markers in file content and `.gitattributes` declarations
//! (docs/built-in-detection.md#generated-code-markers). Only position-bound,
//! documented markers count: free-text checks claimed hand-written code in
//! generators' own repositories (docs/research/generated-code-markers.md).
use super::{decoded_text, relative_path, ParseFailureReason};
use crate::config::{GeneratedEvidence, GeneratedMarker};
use anyhow::Result;
use rayon::prelude::*;
use std::collections::{BTreeMap, BTreeSet};
use std::path::{Path, PathBuf};
use tokei::LanguageType;

mod gitattributes;
mod java;

/// Marker evidence for the counted files among `paths`, keyed by
/// root-relative path. `counted` holds every counted file, whose
/// `.gitattributes` declarations apply whatever their language.
pub(super) fn evidence(
    root: &Path,
    paths: &[PathBuf],
    counted: &BTreeSet<String>,
    config: &tokei::Config,
) -> Result<BTreeMap<String, GeneratedEvidence>> {
    let attributes = gitattributes::Attributes::load(root, counted);
    let content: BTreeMap<String, GeneratedEvidence> = paths
        .iter()
        .filter_map(|path| {
            let language = LanguageType::from_path(path, config)?;
            let name = relative_path(path.strip_prefix(root).ok()?).ok()?;
            counted.contains(&name).then_some((name, language, path))
        })
        .collect::<Vec<_>>()
        .into_par_iter()
        .filter_map(|(name, language, path)| {
            content_marker(language, &name, || {
                decoded_text(path, ParseFailureReason::InvalidEncoding, "source").ok()
            })
            .map(|evidence| (name, evidence))
        })
        .collect();
    let mut evidence = BTreeMap::new();
    for name in counted {
        let declared = attributes.declaration(name);
        let found = match declared {
            Some(gitattributes::Declaration::NotGenerated) => None,
            Some(gitattributes::Declaration::Generated(line)) => {
                content.get(name).cloned().or(Some(GeneratedEvidence {
                    marker: GeneratedMarker::LinguistGenerated,
                    evidence: line,
                }))
            }
            None => content.get(name).cloned(),
        };
        if let Some(found) = found {
            evidence.insert(name.clone(), found);
        }
    }
    Ok(evidence)
}

/// The content marker of a file in `language`, reading its text only when
/// the file name alone does not decide.
fn content_marker(
    language: LanguageType,
    name: &str,
    text: impl FnOnce() -> Option<String>,
) -> Option<GeneratedEvidence> {
    let (marker, evidence) = match language {
        LanguageType::Go => (GeneratedMarker::GoGeneratedHeader, go_header(&text()?)),
        LanguageType::CSharp | LanguageType::VisualBasic => (
            GeneratedMarker::RoslynGenerated,
            roslyn_name(name).or_else(|| roslyn_comment(&text()?)),
        ),
        LanguageType::Java => (
            GeneratedMarker::JavaGeneratedAnnotation,
            java::generated_annotation(&text()?),
        ),
        _ => return None,
    };
    evidence.map(|evidence| GeneratedEvidence { marker, evidence })
}

/// Go's line, `^// Code generated .* DO NOT EDIT\.$`, before the first line
/// that is neither blank nor a comment (`go help generate`).
fn go_header(text: &str) -> Option<String> {
    leading_comments(text, &["//"], false)
        .into_iter()
        .find(|line| {
            line.strip_prefix("// Code generated ")
                .is_some_and(|rest| rest.ends_with(" DO NOT EDIT."))
        })
        .map(String::from)
}

/// Roslyn's file-name rule (`GeneratedCodeUtilities.IsGeneratedCodeFile`):
/// a `TemporaryGeneratedFile_` prefix, or a name before the extension ending
/// `.designer`, `.generated`, `.g` or `.g.i`, ignoring case.
fn roslyn_name(name: &str) -> Option<String> {
    let file = name.rsplit('/').next().unwrap_or(name);
    let lower = file.to_ascii_lowercase();
    let stem = lower.rsplit_once('.').map(|(stem, _)| stem)?;
    (lower.starts_with("temporarygeneratedfile_")
        || [".designer", ".generated", ".g", ".g.i"]
            .iter()
            .any(|suffix| stem.ends_with(suffix)))
    .then(|| file.to_string())
}

/// Roslyn's comment rule (`BeginsWithAutoGeneratedComment`): a comment in the
/// file's leading trivia containing `<autogenerated` or `<auto-generated`,
/// compared ordinally; directives such as `#nullable` may come between.
fn roslyn_comment(text: &str) -> Option<String> {
    leading_comments(text, &["//", "'", "REM "], true)
        .into_iter()
        .find(|line| line.contains("<autogenerated") || line.contains("<auto-generated"))
        .map(|line| line.trim().to_string())
}

/// Lines of the comment block before the first code line, after a
/// byte-order mark. `prefixes` start a comment line; `/*` blocks run to
/// `*/`; `directives` also lets `#` lines through.
fn leading_comments<'a>(text: &'a str, prefixes: &[&str], directives: bool) -> Vec<&'a str> {
    let mut lines = Vec::new();
    let mut in_block = false;
    for line in text.trim_start_matches('\u{feff}').lines() {
        let trimmed = line.trim();
        if in_block {
            lines.push(line);
            in_block = !trimmed.contains("*/");
        } else if trimmed.is_empty() || (directives && trimmed.starts_with('#')) {
            continue;
        } else if let Some(comment) = trimmed.strip_prefix("/*") {
            lines.push(line);
            in_block = !comment.contains("*/");
        } else if prefixes.iter().any(|prefix| trimmed.starts_with(prefix)) {
            lines.push(line);
        } else {
            break;
        }
    }
    lines
}
