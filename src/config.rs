/// Configuration file discovered in the scan root.
pub const CONFIG_FILE: &str = ".locmetryrc";

/// Provenance of files that no entry matched.
const FALLBACK: &str = "fallback";

/// Provenance prefix of built-in test and build conventions.
const BUILTIN: &str = "builtin:";

const DEFAULT_EXCLUDES: &[&str] = &["**/.git/**", "**/node_modules/**", "**/.build/**"];

/// A built-in classification entry; configuration `version = 1` pins each set.
struct Convention {
    id: &'static str,
    patterns: &'static [&'static str],
    purpose: Purpose,
    category: &'static str,
}

const fn test_convention(id: &'static str, patterns: &'static [&'static str]) -> Convention {
    Convention {
        id,
        patterns,
        purpose: Purpose::Test,
        category: "test",
    }
}

/// Version-1 test conventions.
///
/// Ambiguous names are deliberately absent: reference projects disagree on
/// whether `fixtures` hold tests, and one keeps specification tooling in a
/// `spec` folder (PRODUCT.md; docs/research/local, 2026-10-15).
const BUILTIN_TESTS_V1: &[Convention] = &[
    test_convention("test-directory", &["**/{test,tests,__test__,__tests__}/**"]),
    test_convention(
        "gradle-test-source-set",
        &["**/src/*Test/**", "**/src/testFixtures/**"],
    ),
    test_convention("snapshot-directory", &["**/__snapshots__/**"]),
    test_convention(
        "js-test-file",
        &["**/*.{test,spec}.{js,jsx,mjs,cjs,ts,tsx,mts,cts}"],
    ),
    test_convention(
        "jvm-test-class",
        &["**/*{Test,Tests,TestCase}.{java,kt,kts,groovy,scala}"],
    ),
    test_convention("go-test-file", &["**/*_test.go"]),
    test_convention(
        "python-test-file",
        &["**/test_*.py", "**/*_test.py", "**/conftest.py"],
    ),
];

/// Version-1 build conventions, applied after test conventions.
///
/// Build scripts are maintained but are not implementation, and wrapper
/// scripts are generated by their build tool; every reference profile wrote
/// equivalent rules by hand (docs/research/local, 2026-10-15).
const BUILTIN_BUILD_V1: &[Convention] = &[
    Convention {
        id: "build-script",
        patterns: &[
            "**/{build,settings}.gradle",
            "**/{build,settings}.gradle.kts",
            "**/pom.xml",
            "**/CMakeLists.txt",
            "**/*.cmake",
            "**/{Makefile,makefile,GNUmakefile}",
        ],
        purpose: Purpose::Production,
        category: "build-tooling",
    },
    Convention {
        id: "build-wrapper",
        patterns: &[
            "**/{gradlew,gradlew.bat,mvnw,mvnw.cmd}",
            "**/gradle/wrapper/**",
            "**/.mvn/wrapper/**",
        ],
        purpose: Purpose::Unclassified,
        category: "third-party-wrapper",
    },
];

/// Version-1 language mappings for files Tokei 15.0.0 does not recognize.
///
/// Each was selected but uncounted in the reference projects' coverage reports
/// (docs/research/local, 2026-10-15); the mapped language's syntax matches.
const BUILTIN_LANGUAGES_V1: &[(&str, &[&str], LanguageType)] = &[
    ("gradle-script", &["**/*.gradle"], LanguageType::Groovy),
    ("jsonc", &["**/*.jsonc"], LanguageType::Json),
    ("json-lines", &["**/*.jsonl"], LanguageType::Json),
    ("java-properties", &["**/*.properties"], LanguageType::Ini),
];

#[derive(Clone, Copy, Debug, Deserialize, Serialize, PartialEq, Eq, PartialOrd, Ord)]
#[serde(rename_all = "lowercase")]
pub enum Purpose {
    Production,
    Test,
    Unclassified,
}

impl Purpose {
    pub const ALL: [Self; 3] = [Self::Production, Self::Test, Self::Unclassified];
}

impl fmt::Display for Purpose {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(match self {
            Self::Production => "production",
            Self::Test => "test",
            Self::Unclassified => "unclassified",
        })
    }
}

#[derive(Debug, Serialize)]
pub struct Classification {
    pub purpose: Purpose,
    pub category: String,
    pub rule: String,
}

/// Selection settings of the `[scope]` table.
#[derive(Clone, Debug, Deserialize, Serialize)]
#[serde(default, deny_unknown_fields)]
pub struct ScopeSettings {
    pub hidden: bool,
    pub respect_ignore_files: bool,
    pub default_excludes: bool,
    pub exclude: Vec<String>,
}

impl Default for ScopeSettings {
    fn default() -> Self {
        Self {
            hidden: true,
            respect_ignore_files: true,
            default_excludes: true,
            exclude: Vec::new(),
        }
    }
}

