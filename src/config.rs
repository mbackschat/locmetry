/// A built-in classification entry. The configuration `version` selects each
/// set, and releases may only add entries to it (PRODUCT.md, `version`).
struct Convention {
    id: &'static str,
    patterns: &'static [&'static str],
    purpose: Purpose,
    category: &'static str,
}

const fn test_convention(id: &'static str, patterns: &'static [&'static str]) -> Convention {
    Convention {
        id,
        patterns,
        purpose: Purpose::Test,
        category: "test",
    }
}

