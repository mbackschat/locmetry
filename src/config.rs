/// Personal defaults: settings that only narrow scope or teach languages, so
/// a project is classified the same way for everyone (PRODUCT.md, User Defaults).
#[derive(Debug, Deserialize)]
#[serde(deny_unknown_fields)]
struct UserDefaults {
    version: u32,
    #[serde(default)]
    scope: UserScope,
    #[serde(default)]
    languages: UserLanguages,
}

#[derive(Debug, Default, Deserialize)]
#[serde(deny_unknown_fields)]
struct UserScope {
    #[serde(default)]
    exclude: Vec<String>,
}

#[derive(Debug, Default, Deserialize)]
#[serde(deny_unknown_fields)]
struct UserLanguages {
    #[serde(default)]
    mappings: Vec<MappingConfig>,
}

impl UserDefaults {
    fn load(path: &Path) -> Result<Self> {
        let input = std::fs::read_to_string(path)
            .with_context(|| format!("Cannot read user defaults {}", path.display()))?;
        let defaults: Self = toml::from_str(&input).with_context(|| {
            format!(
                "Invalid user defaults {}; they may set only `version`, `scope.exclude`, and `[[languages.mappings]]`",
                path.display()
            )
        })?;
        ensure!(
            defaults.version == 1,
            "Unsupported version {} in user defaults {}",
            defaults.version,
            path.display()
        );
        Ok(defaults)
    }

    /// Adds user exclusions before the project's and user mappings after the
    /// project's, so the project's own mappings take precedence.
    fn merge_into(self, config: &mut ConfigFile, path: &Path) -> Result<()> {
        for mapping in &self.languages.mappings {
            ensure!(
                config
                    .languages
                    .mappings
                    .iter()
                    .all(|project| project.id != mapping.id),
                "Language mapping {:?} in user defaults {} is also defined by the project",
                mapping.id,
                path.display()
            );
        }
        config.scope.exclude.splice(0..0, self.scope.exclude);
        config.languages.mappings.extend(self.languages.mappings);
        Ok(())
    }
}

/// The user defaults file: `$XDG_CONFIG_HOME/locmetry/config.toml`, else
/// `~/.config/locmetry/config.toml`, on every platform (PRODUCT.md). A relative
/// `XDG_CONFIG_HOME` is ignored, as the XDG Base Directory specification requires.
pub fn user_defaults_file() -> Option<PathBuf> {
    let base = std::env::var_os("XDG_CONFIG_HOME")
        .map(PathBuf::from)
        .filter(|path| path.is_absolute())
        .or_else(|| std::env::var_os("HOME").map(|home| PathBuf::from(home).join(".config")))?;
    Some(base.join("locmetry").join("config.toml"))
}

/// Escapes glob metacharacters so `path` matches only itself.
pub(crate) fn literal_glob(path: &str) -> String {
    path.chars().fold(String::new(), |mut literal, character| {
        if "\\*?[]{}!".contains(character) {
            literal.push('\\');
        }
        literal.push(character);
        literal
    })
}

/// Compiles a root-relative glob with the separator semantics of PRODUCT.md.
///
/// globset lets `*` cross `/` and makes `\` platform-dependent by default
/// (globset 0.4 `GlobBuilder` docs), so both options are set explicitly.
fn glob(pattern: &str) -> Result<Glob> {
    ensure!(
        !pattern.starts_with('!'),
        "Pattern {pattern:?} uses negation, which is not supported"
    );
    ensure!(
        !pattern.starts_with('/')
            && pattern
                .split('/')
                .all(|part| !matches!(part, "" | "." | "..")),
        "Pattern {pattern:?} must be a relative path glob without empty, `.`, or `..` segments"
    );
    GlobBuilder::new(pattern)
        .literal_separator(true)
        .backslash_escape(true)
        .build()
        .with_context(|| format!("Invalid glob {pattern:?}"))
}

fn glob_set<'a>(patterns: impl IntoIterator<Item = &'a str>) -> Result<GlobSet> {
    let mut set = GlobSetBuilder::new();
    for pattern in patterns {
        set.add(glob(pattern)?);
    }
    Ok(set.build()?)
}

/// Compiled selection policy.
#[derive(Clone, Debug)]
pub struct Scope {
    settings: ScopeSettings,
    excludes: GlobSet,
    /// Directories whose every descendant is excluded, from `<dir>/**` patterns.
    pruned_directories: GlobSet,
}

impl Scope {
    fn new(settings: ScopeSettings) -> Result<Self> {
        let patterns = Self::patterns(&settings);
        let excludes =
            glob_set(patterns.iter().map(String::as_str)).context("Invalid scope exclusion")?;
        let pruned_directories = glob_set(
            patterns
                .iter()
                .filter_map(|pattern| pattern.strip_suffix("/**")),
        )?;
        Ok(Self {
            settings,
            excludes,
            pruned_directories,
        })
    }

    fn patterns(settings: &ScopeSettings) -> Vec<String> {
        let defaults = DEFAULT_EXCLUDES
            .iter()
            .filter(|_| settings.default_excludes)
            .map(|pattern| pattern.to_string());
        defaults.chain(settings.exclude.iter().cloned()).collect()
    }

    pub fn hidden(&self) -> bool {
        self.settings.hidden
    }

    pub fn respect_ignore_files(&self) -> bool {
        self.settings.respect_ignore_files
    }

    /// Effective exclusion patterns, defaults first.
    pub fn exclusions(&self) -> Vec<String> {
        Self::patterns(&self.settings)
    }

    pub fn is_excluded(&self, path: &str) -> bool {
        self.excludes.is_match(path)
    }

    pub fn prunes_directory(&self, path: &str) -> bool {
        self.pruned_directories.is_match(path)
    }
}

#[derive(Debug)]
struct Entry {
    id: String,
    matcher: GlobSet,
    kinds: Option<Vec<Kind>>,
    purpose: Purpose,
    category: String,
}

impl Entry {
    fn matches(&self, path: &str, kind: Kind) -> bool {
        self.matcher.is_match(path)
            && self
                .kinds
                .as_ref()
                .is_none_or(|kinds| kinds.contains(&kind))
    }

    fn classification(&self) -> Classification {
        Classification {
            purpose: self.purpose,
            category: self.category.clone(),
            rule: self.id.clone(),
        }
    }

    fn from_config(entry: &EntryConfig) -> Result<Self> {
        ensure!(
            !entry.patterns.is_empty(),
            "Entry {} needs a nonempty match array",
            entry.id
        );
        ensure!(
            entry.kind.as_ref().is_none_or(|kinds| !kinds.is_empty()),
            "Entry {} needs a nonempty kind array when kind is present",
            entry.id
        );
        Ok(Self {
            id: entry.id.clone(),
            matcher: glob_set(entry.patterns.iter().map(String::as_str))
                .with_context(|| format!("Invalid match in entry {}", entry.id))?,
            kinds: entry.kind.clone(),
            purpose: entry.purpose,
            category: entry
                .category
                .clone()
                .unwrap_or_else(|| entry.purpose.to_string()),
        })
    }
}

/// Rejects empty, duplicate, and reserved entry IDs across all stages.
fn check_ids<'a>(ids: impl IntoIterator<Item = &'a str>) -> Result<()> {
    let mut seen = BTreeSet::new();
    for id in ids {
        ensure!(
            !id.is_empty() && seen.insert(id),
            "Entry IDs must be nonempty and unique: {id:?}"
        );
        ensure!(
            id != FALLBACK && !id.starts_with(BUILTIN),
            "Entry ID {id:?} is reserved for {FALLBACK} or {BUILTIN} provenance"
        );
    }
    Ok(())
}

/// Scope and classification for one measurement.
#[derive(Debug)]
pub struct Policy {
    scope: Scope,
    overrides: Vec<Entry>,
    /// Built-in test conventions, then built-in build conventions.
    conventions: Vec<Entry>,
    rules: Vec<Entry>,
    /// Whether build descriptors may declare production source.
    detect_modules: bool,
    /// Modules adopted from the scan; empty when detection is disabled.
    modules: Vec<Module>,
    /// One production entry per detector, after rules and before the fallback.
    module_entries: Vec<Entry>,
    fallback: (Purpose, String),
    /// Project mappings first, then built-in ones.
    languages: Vec<LanguageMapping>,
    snapshot: Value,
}

impl Policy {
    /// Built-in settings used when no configuration file exists.
    pub fn defaults() -> Self {
        Self::from_toml("version = 1").expect("built-in configuration is valid")
    }

    pub fn from_toml(input: &str) -> Result<Self> {
        Self::from_config(toml::from_str(input).context("Invalid TOML configuration")?)
    }

    fn from_config(config: ConfigFile) -> Result<Self> {
        ensure!(
            config.version == 1,
            "Unsupported configuration version {}",
            config.version
        );
        check_ids(
            config
                .overrides
                .iter()
                .chain(&config.rules)
                .map(|entry| entry.id.as_str()),
        )?;
        let entries = |list: &[EntryConfig]| {
            list.iter()
                .map(Entry::from_config)
                .collect::<Result<Vec<_>>>()
        };
        let conventions = [
            (config.classification.builtin_tests, BUILTIN_TESTS_V1),
            (config.classification.builtin_build, BUILTIN_BUILD_V1),
        ]
        .into_iter()
        .filter(|(enabled, _)| *enabled)
        .flat_map(|(_, set)| set.iter())
        .collect::<Vec<_>>();
        let convention_snapshot = json!(conventions
            .iter()
            .map(|convention| json!({
                "id": format!("{BUILTIN}{}", convention.id),
                "match": convention.patterns,
                "purpose": convention.purpose,
                "category": convention.category,
            }))
            .collect::<Vec<_>>());
        let conventions = conventions
            .into_iter()
            .map(|convention| {
                Ok(Entry {
                    id: format!("{BUILTIN}{}", convention.id),
                    matcher: glob_set(convention.patterns.iter().copied())?,
                    kinds: None,
                    purpose: convention.purpose,
                    category: convention.category.into(),
                })
            })
            .collect::<Result<Vec<_>>>()?;
        check_ids(
            config
                .languages
                .mappings
                .iter()
                .map(|mapping| mapping.id.as_str()),
        )?;
        let mut languages = config
            .languages
            .mappings
            .iter()
            .map(|mapping| {
                ensure!(
                    !mapping.patterns.is_empty(),
                    "Language mapping {} needs a nonempty match array",
                    mapping.id
                );
                Ok(LanguageMapping {
                    id: mapping.id.clone(),
                    matcher: glob_set(mapping.patterns.iter().map(String::as_str)).with_context(
                        || format!("Invalid match in language mapping {}", mapping.id),
                    )?,
                    language: LanguageType::from_name(&mapping.language).with_context(|| {
                        format!(
                            "Unknown language {:?} in language mapping {}",
                            mapping.language, mapping.id
                        )
                    })?,
                })
            })
            .collect::<Result<Vec<_>>>()?;
        let builtin_languages = BUILTIN_LANGUAGES_V1
            .iter()
            .filter(|_| config.languages.builtin)
            .collect::<Vec<_>>();
        for (id, patterns, language) in &builtin_languages {
            languages.push(LanguageMapping {
                id: format!("{BUILTIN}{id}"),
                matcher: glob_set(patterns.iter().copied())?,
                language: *language,
            });
        }
        let mut snapshot = serde_json::to_value(&config)?;
        snapshot["builtin_language_mappings"] = json!(builtin_languages
            .iter()
            .map(|(id, patterns, language)| {
                json!({"id": format!("{BUILTIN}{id}"), "match": patterns, "language": language.name()})
            })
            .collect::<Vec<_>>());
        snapshot["builtin_conventions"] = convention_snapshot;
        let fallback = config.classification.fallback;
        Ok(Self {
            scope: Scope::new(config.scope.clone())?,
            overrides: entries(&config.overrides)?,
            conventions,
            rules: entries(&config.rules)?,
            detect_modules: config.classification.builtin_modules,
            modules: Vec::new(),
            module_entries: Vec::new(),
            fallback: (fallback, fallback.to_string()),
            languages,
            snapshot,
        })
    }

    /// Loads an explicit or discovered TOML configuration file.
    pub fn load(path: &Path) -> Result<Self> {
        Self::load_layers(Some(path), None)
    }

    /// Builds the policy from an optional project configuration merged with
    /// optional user defaults; without either, built-in settings apply.
    pub fn load_layers(project: Option<&Path>, user: Option<&Path>) -> Result<Self> {
        let mut config: ConfigFile = match project {
            Some(path) => {
                // JSON/regex profiles were retired after strict TOML translations
                // reproduced every reviewed classification (PLAN.md section 4).
                ensure!(
                    path.extension().is_none_or(|extension| extension != "json"),
                    "{} looks like a retired JSON/regex profile; translate it to TOML (PRODUCT.md)",
                    path.display()
                );
                let input = std::fs::read_to_string(path)
                    .with_context(|| format!("Cannot read configuration {}", path.display()))?;
                toml::from_str(&input)
                    .with_context(|| format!("Invalid configuration {}", path.display()))?
            }
            None => toml::from_str("version = 1").expect("built-in configuration is valid"),
        };
        if let Some(path) = user {
            UserDefaults::load(path)?.merge_into(&mut config, path)?;
        }
        let sources: Vec<String> = [project, user]
            .into_iter()
            .flatten()
            .map(|path| path.display().to_string())
            .collect();
        Self::from_config(config)
            .with_context(|| format!("Invalid configuration {}", sources.join(" with ")))
    }

    pub fn override_scope(&mut self, overrides: &ScopeOverrides) -> Result<()> {
        let mut settings = self.scope.settings.clone();
        if let Some(hidden) = overrides.hidden {
            settings.hidden = hidden;
        }
        if let Some(respect) = overrides.respect_ignore_files {
            settings.respect_ignore_files = respect;
        }
        settings.exclude.extend(overrides.exclude.iter().cloned());
        self.scope = Scope::new(settings)?;
        Ok(())
    }

    /// Excludes the loaded configuration file when it lies inside the
    /// canonical scan `root`.
    ///
    /// The configuration is measurement policy, not project content. Its path
    /// is escaped so glob metacharacters in its name match only itself.
    pub fn exclude_configuration(&mut self, root: &Path, config: &Path) -> Result<()> {
        let config = config
            .canonicalize()
            .with_context(|| format!("Cannot resolve configuration {}", config.display()))?;
        let Ok(relative) = config.strip_prefix(root) else {
            return Ok(());
        };
        self.override_scope(&ScopeOverrides {
            exclude: vec![literal_glob(&relative_path(relative)?)],
            ..Default::default()
        })
    }

    /// Adopts the modules a scan detected, unless `builtin_modules = false`.
    ///
    /// Their production source is classified after the project's rules, so
    /// project knowledge wins and only files that would otherwise reach the
    /// fallback change (PRODUCT.md, Matching and Precedence).
    pub fn adopt_modules(&mut self, modules: &[Module]) -> Result<()> {
        if !self.detect_modules {
            return Ok(());
        }
        let mut sources = std::collections::BTreeMap::<&str, Vec<&str>>::new();
        for module in modules {
            sources
                .entry(module.detector)
                .or_default()
                .extend(module.sources.iter().map(String::as_str));
        }
        self.module_entries = sources
            .into_iter()
            .map(|(detector, globs)| {
                Ok(Entry {
                    id: format!("{BUILTIN}{detector}-module"),
                    matcher: glob_set(globs)?,
                    kinds: None,
                    purpose: Purpose::Production,
                    category: "implementation".into(),
                })
            })
            .collect::<Result<_>>()?;
        self.modules = modules.to_vec();
        Ok(())
    }

    /// Modules whose source this policy classifies.
    pub fn modules(&self) -> &[Module] {
        &self.modules
    }

    pub fn classify(&self, path: &str, kind: Kind) -> Classification {
        let stages = [
            &self.overrides,
            &self.conventions,
            &self.rules,
            &self.module_entries,
        ];
        match stages
            .into_iter()
            .flatten()
            .find(|entry| entry.matches(path, kind))
        {
            Some(entry) => entry.classification(),
            None => Classification {
                purpose: self.fallback.0,
                category: self.fallback.1.clone(),
                rule: FALLBACK.into(),
            },
        }
    }

    pub fn is_excluded(&self, path: &str) -> bool {
        self.scope.is_excluded(path)
    }

    /// Language and mapping ID for a file the backend does not recognize.
    pub fn mapped_language(&self, path: &str) -> Option<(&str, LanguageType)> {
        self.languages
            .iter()
            .find(|mapping| mapping.matcher.is_match(path))
            .map(|mapping| (mapping.id.as_str(), mapping.language))
    }

    pub fn scope(&self) -> &Scope {
        &self.scope
    }

    pub fn snapshot(&self) -> &Value {
        &self.snapshot
    }
}
